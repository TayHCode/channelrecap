"""Write agent instructions without replacing a user's own instructions."""
from pathlib import Path
from . import NAME
from .words import package_text


def write_agent_files(out_dir: Path) -> None:
    marker = f"<!-- generated by {NAME} -->"
    pointer = marker + "\nWhen asked to analyze these videos, read `AGENT_PROMPT.md` in this folder and follow it exactly.\n"
    for name, content in (("AGENT_PROMPT.md", package_text("agent_prompt.md")), ("AGENTS.md", pointer), ("CLAUDE.md", pointer)):
        path = out_dir / name
        if path.exists():
            with path.open(encoding="utf-8") as stream:
                first = stream.readline().rstrip("\n")
            if first != marker:
                print(f"note: keeping user-written {name}")
                continue
        path.write_text(content, encoding="utf-8", newline="\n")
