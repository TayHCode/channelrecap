import helpers
import contextlib
import io
from pathlib import Path
import tempfile
import unittest
from channelrecap.agentfiles import write_agent_files
from channelrecap.words import package_text
from channelrecap.citations import parse_claim, SECTIONS
from channelrecap import NAME


class AgentTests(unittest.TestCase):
    def test_prompt_pointers_and_overwrite(self) -> None:
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder)
            write_agent_files(root)
            prompt = (root / 'AGENT_PROMPT.md').read_text(encoding='utf-8')
            self.assertEqual(prompt, package_text('agent_prompt.md'))
            for n in range(1,7):
                self.assertIn(f'### {n}. ',prompt)
            example = next(line for line in prompt.splitlines() if line.startswith('- Plain claim. | '))
            self.assertEqual(len(parse_claim(example.replace('video-id','sample').replace('HH:MM:SS','00:01:00'))), 1)
            for heading in SECTIONS:
                self.assertIn(heading, prompt)
            expected = f'<!-- generated by {NAME} -->\nWhen asked to analyze these videos, read `AGENT_PROMPT.md` in this folder and follow it exactly.\n'
            self.assertEqual((root / 'AGENTS.md').read_text(encoding='utf-8'), expected)
            self.assertEqual((root / 'CLAUDE.md').read_text(encoding='utf-8'), expected)
            for name in ['AGENTS.md','CLAUDE.md','AGENT_PROMPT.md']:
                (root / name).write_text('My instructions\n', encoding='utf-8')
            with contextlib.redirect_stdout(io.StringIO()) as err:
                write_agent_files(root)
            self.assertEqual(err.getvalue().count('keeping user-written'),3)
            self.assertEqual((root / 'AGENT_PROMPT.md').read_text(encoding='utf-8'),'My instructions\n')
